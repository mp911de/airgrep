#!/usr/bin/env python3
"""Turn the greetings catalog greetings.json into a C++ header for the display.
"""

import argparse
import json
from pathlib import Path
import sys

PLACEHOLDER = "{callsign}"


def literal(text):
    return json.dumps(text, ensure_ascii=False)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("catalog", type=Path)
    parser.add_argument("header", type=Path)
    parser.add_argument("--longest", type=int, required=True, metavar="CHARACTERS",
                        help="Room for a greeting without the callsign")
    parser.add_argument("--longest-named", type=int, required=True, metavar="CHARACTERS",
                        help=f"Room for a greeting with {PLACEHOLDER}, not counting the callsign")
    args = parser.parse_args(argv)
    catalog = json.loads(args.catalog.read_text(encoding="utf-8"))
    failures = []
    for language, greetings in catalog.items():
        if not any(PLACEHOLDER not in greeting for greeting in greetings):
            failures.append(f"{language} has no greeting without {PLACEHOLDER}")
        for greeting in greetings:
            named = PLACEHOLDER in greeting
            length, room = len(greeting.replace(PLACEHOLDER, "")), args.longest_named if named else args.longest
            if length > room:
                failures.append(f"{language}: {length} characters, room for {room}: {greeting}")
    for failure in failures:
        print(f"{args.catalog}: {failure}", file=sys.stderr)
    if failures:
        return 1

    lines = [f"// Generated by tools/greetings.py from {args.catalog.name}.", "#pragma once", "", "#include <span>", "",
             "namespace display::greetings {",
             "// In a greeting, the own callsign. A greeting with it needs one stored.",
             f"inline constexpr char PLACEHOLDER[] = {literal(PLACEHOLDER)};", "",
             "struct Language {", "\tconst char* code;", "\tstd::span<const char* const> greetings;", "};", ""]
    for language, greetings in catalog.items():
        lines.append(f"inline constexpr const char* {language.upper()}[] = {{")
        lines += [f"\t{literal(greeting)}," for greeting in greetings]
        lines += ["};", ""]
    lines.append("// The first one is for a language without greetings.")
    lines.append("inline constexpr Language LANGUAGES[] = {")
    lines += [f"\t{{{literal(language)}, {language.upper()}}}," for language in catalog]
    lines += ["};", "}  // namespace display::greetings", ""]
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text("\n".join(lines), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
